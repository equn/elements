#!/usr/bin/env bash
# Deploy: elements/site/index.html  ->  NY server  /www/wwwroot/equn.me/elements/
# Public URL: https://equn.me/elements/
#
# Usage:  ./deploy.sh [-y] [--no-purge] [-n|--dry-run] [--skip-checks]
#
# What is published
# -----------------
# site/index.html plus site/.htaccess. The page is a single self-contained page - CSS, JS and the
# whole 118-element dataset are inlined at build time - so nothing else needs
# to go up. site/app.css, app.js, shell.html and syllables.json are BUILD
# SOURCES; publishing them would ship a second, confusing copy of the site.
# The repo root (elements.json, ELEMENTS.md, README.md, data/, build.py) is the
# database and its dev notes, not a website.
#
# So this stages a two-file tree rather than pointing rsync at site/.
# .htaccess sets Cache-Control: no-cache on the page - see Cache below.
#
# Preflight
# ---------
# index.html is GENERATED by build.py. The easy mistake with this repo is to
# edit app.js or app.css and deploy without rebuilding, publishing a stale page
# that silently lacks the change. So this refuses to deploy unless:
#
#   * index.html exists and is a plausible size;
#   * it is NEWER than every build input (app.css, app.js, shell.html,
#     syllables.json, elements.json, build.py);
#   * it is pure ASCII - the page carries Chinese as \uXXXX escapes precisely
#     because the host supplies <head> and we cannot declare a charset. A
#     non-ASCII byte here means someone bypassed build.py and the Chinese
#     would render as mojibake on a server that serves it as anything but UTF-8;
#   * it declares a viewport (else it lays out 980px wide on a phone);
#   * it still contains all 118 elements and a <title>.
#
# --skip-checks exists for republishing when you know better. It prints a loud
# warning; do not use it to push past a failure.
#
# Cache
# -----
# One file, no sub-resources, so there is nothing to fingerprint. Cloudflare
# does not edge-cache the HTML (cf-cache-status: DYNAMIC), but BROWSERS did: the
# server sent no Cache-Control, only Last-Modified, so phones guessed a freshness
# window and kept serving the previous deploy. site/.htaccess fixes that with
# no-cache (revalidate every visit). If index.html is ever split into separate
# assets, fingerprint them here the way star-neighbors does.

set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
# shellcheck disable=SC1091
source "$SCRIPT_DIR/../vpshosts/deploy-lib.sh"
_require_secrets

APP_NAME="elements"
SSH_HOST="ny"
REMOTE_TARGET="/www/wwwroot/equn.me/elements/"
CF_ZONE_ID="${CF_ZONE_EQUN_ME:-}"

EXCLUDES=( "${DEFAULT_EXCLUDES[@]}" )

SKIP_CHECKS=false
DRY_RUN=false
ARGS=()
for a in "$@"; do
  case "$a" in
    --skip-checks) SKIP_CHECKS=true ;;
    -n|--dry-run)  DRY_RUN=true; ARGS+=("$a") ;;
    *) ARGS+=("$a") ;;
  esac
done

PAGE="$SCRIPT_DIR/site/index.html"

preflight() {
  [ -f "$PAGE" ] || { _err "site/index.html is missing. Run: python3 build.py"; exit 1; }

  local bytes
  bytes=$(wc -c < "$PAGE" | tr -d ' ')
  if [ "$bytes" -lt 150000 ]; then
    _err "site/index.html is only ${bytes} bytes - the data payload looks absent."
    _err "Run: python3 build.py"
    exit 1
  fi

  # generated file must not predate its inputs
  local stale=()
  for src in site/app.css site/app.js site/shell.html site/syllables.json elements.json build.py; do
    [ -f "$SCRIPT_DIR/$src" ] || continue
    [ "$SCRIPT_DIR/$src" -nt "$PAGE" ] && stale+=("$src")
  done
  if [ ${#stale[@]} -gt 0 ]; then
    _err "site/index.html is older than: ${stale[*]}"
    _err "It is generated - deploying now would publish a stale page."
    _err "Run: python3 build.py"
    exit 1
  fi

  python3 - "$PAGE" <<'PY' || exit 1
import sys, re
p = sys.argv[1]
raw = open(p, 'rb').read()
html = raw.decode('utf-8')
fail = []

non_ascii = [c for c in set(html) if ord(c) > 127]
if non_ascii:
    fail.append(f"{len(non_ascii)} non-ASCII characters present "
                f"({''.join(non_ascii[:6])}) - build.py escapes these on purpose")

if not re.search(r'<title>[^<]+</title>', html[:8192]):
    fail.append("no <title> in the first 8KB")
if 'name="viewport"' not in html:
    fail.append("no viewport meta - the page would lay out 980px wide on a phone")

m = re.search(r'const ELEMENTS=(\[.*?\]);\n', html, re.S)
if not m:
    fail.append("the ELEMENTS payload is missing")
else:
    import json
    try:
        els = json.loads(m.group(1))
        if len(els) != 118:
            fail.append(f"{len(els)} elements in the payload, expected 118")
        elif not all(e.get('zh') for e in els):
            fail.append("some elements have no Chinese name")
    except Exception as ex:
        fail.append(f"the ELEMENTS payload does not parse: {ex}")

if fail:
    for f in fail:
        print(f"ERROR: {f}", file=sys.stderr)
    sys.exit(1)

print(f"    {len(raw)//1024} KB · 118 elements · ASCII-only · viewport declared")
PY
}

STAGE="$(mktemp -d "${TMPDIR:-/tmp}/elements-deploy.XXXXXX")"
trap 'rm -rf "$STAGE"' EXIT

build_stage() {
  _log "Staging the publishable tree..."
  cp "$PAGE" "$STAGE/index.html"
  if [ -f "$SCRIPT_DIR/site/.htaccess" ]; then
    cp "$SCRIPT_DIR/site/.htaccess" "$STAGE/.htaccess"
  else
    _warn "site/.htaccess missing - browsers will guess cache lifetimes again"
  fi
  _log "    staged $(find "$STAGE" -type f | wc -l | tr -d ' ') files, $(du -sh "$STAGE" | cut -f1)"
}

if [ "$SKIP_CHECKS" = true ]; then
  _warn "--skip-checks: publishing without verifying the build."
else
  _log "Verifying the built page before publishing..."
  preflight
fi
build_stage

LOCAL_DIR="$STAGE/"
deploy_app "${ARGS[@]+"${ARGS[@]}"}"

if [ "$DRY_RUN" = false ]; then
  printf '\n'
  _log "Live at https://equn.me/elements/"
fi
